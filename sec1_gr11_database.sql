DROP DATABASE IF EXISTS lsdb;
CREATE DATABASE lsdb;

USE lsdb;

CREATE TABLE IF NOT EXISTS adm_information (
    uid 			VARCHAR(50) PRIMARY KEY,
    first_name 		VARCHAR(50) NOT NULL,
    last_name 		VARCHAR(50) NOT NULL,
    age 			INT,
    gender			CHAR(1)	 	 NOT NULL,
    phone			VARCHAR(255),
    email 			VARCHAR(255) NOT NULL,
    CONSTRAINT check_uid CHECK (uid REGEXP '^[a][A-Za-z0-9_]*$')
);

CREATE TABLE IF NOT EXISTS adm_login (
    login_id 		VARCHAR(50) NOT NULL PRIMARY KEY,
    pass 			VARCHAR(50) NOT NULL,
    login_role 		ENUM('Boss', 'Product Manager','Tester') NOT NULL,
    
    CONSTRAINT check_login_id CHECK (login_id REGEXP '^[a][A-Za-z0-9_]*$'),
    CONSTRAINT fk_id  FOREIGN KEY (login_id) REFERENCES adm_information(uid)
);

CREATE TABLE IF NOT EXISTS country (
	c_id 		CHAR(2) PRIMARY KEY,
    c_name 		VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS address (
    address_id 		INT PRIMARY KEY,
    street 			VARCHAR(255) NOT NULL,
    city 			VARCHAR(255) NOT NULL,
    state 			VARCHAR(255) NOT NULL,
    add_country 	CHAR(2) NOT NULL,
    zip_code 		VARCHAR(10) NOT NULL,
    add_uid			VARCHAR(50) NOT NULL,
    
    CONSTRAINT fk_add_uid FOREIGN KEY (add_uid) REFERENCES adm_information(uid),
    CONSTRAINT fk_country  FOREIGN KEY (add_country) REFERENCES country(c_id)
);

CREATE TABLE IF NOT EXISTS report(
	rep_id			INT PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS product (
	p_id			INT PRIMARY KEY,
    p_name			VARCHAR(255) NOT NULL,
    p_des			VARCHAR(255) ,
    rating			CHAR(7) NOT NULL,
    p_type			VARCHAR(255) NOT NULL,
    p_color			VARCHAR(255) NOT NULL,
    p_inches		VARCHAR(255) NOT NULL,
    p_memory		VARCHAR(255) NOT NULL,
    p_internet		VARCHAR(255) NOT NULL,
    p_price			DOUBLE NOT NULL,
    p_reportid		INT NOT NULL,
    
    CONSTRAINT fk_p_repid FOREIGN KEY (p_reportid) REFERENCES report(rep_id)
);


